-- Reference list of public-sector organisations a user can pick from at registration, with the
-- primary email domain each one uses. Kept apart from organisation: that table holds whatever
-- registrants have typed (V1.010), whereas this one is curated and only changes by migration.
--
-- primary_domain is deliberately not unique - several bodies share one (HMCTS, HMPPS and the
-- Legal Aid Agency all sit on justice.gov.uk alongside the Ministry of Justice).
--
-- Bodies are renamed, merged and closed by machinery-of-government changes; set active to false
-- to retire one from the picker rather than deleting a row that users may already reference.
create table organisation_lookup (
    id                  serial  primary key,
    organisation_type   text    not null,
    name                text    not null,
    primary_domain      text    not null,
    active              boolean not null default true
);

create unique index organisation_lookup_name_lower_idx on organisation_lookup (lower(name));
create index organisation_lookup_primary_domain_idx on organisation_lookup (lower(primary_domain));

